"""GUI-kontroller med tydligt fiktiv demobackend. Inga Thunderbird-konton används."""
from pathlib import Path
from playwright.sync_api import sync_playwright
import json,tempfile
ROOT=Path(__file__).resolve().parents[1]
checks=[]
def check(condition,name):
    assert condition,name
    checks.append(name);print('PASS:',name)
with sync_playwright() as p:
    b=p.chromium.launch(headless=True,args=['--no-sandbox'])
    page=b.new_page(viewport={'width':1440,'height':1120})
    errors=[];external=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:external.append(r.url) if r.url.startswith(('http:','https:')) else None)
    page.on('dialog',lambda d:d.accept())
    page.goto((ROOT/'addon'/'ui.html').as_uri()+'?demo=1')
    page.wait_for_function("document.getElementById('ruleName').value==='Fortnox fakturor'")
    check(page.locator('#demoBanner').is_visible(),'preview explicitly labelled')
    check(page.locator('.rule-row').count()==3 and page.locator('#countRules').inner_text()=='3','rule list and enabled count')
    check('Testläge' in page.locator('#statusPill').inner_text(),'default test mode is visible')
    page.click('#test');page.wait_for_selector('#testResult:not([hidden])')
    check('fortfarande öppet' in page.locator('#testResult').inner_text(),'test explains displayed-message guard')
    check(page.locator('#countMoved').inner_text()=='0','test does not claim a move')
    check(page.locator('.branch-row').count()==2,'demo rule shows its saved branch rows')
    check(page.locator('#templateBar .template-btn').count()==6,'no template turns on year archiving')
    page.click('.rule-open:has-text("Arkivera äldre mejl")')
    check(not page.locator('#ruleYearFolders').is_checked(),'year folders are optional and off by default')
    check(page.locator('#ruleMoveUnread').is_checked() is False,'unread mail waits while the box is unticked')
    check('Endast lästa' in page.locator('#ruleReadFilter option:checked').inner_text(),'archive rule waits for unread mail to be read')
    page.locator('#ruleMoveUnread').check();page.wait_for_timeout(100)
    check(page.locator('#ruleReadFilter').input_value()=='both','ticking the box makes unread mail move right away')
    check('flyttas direkt' in page.locator('#unreadMoveNote, [data-i18n=unreadMoveNote]').first.inner_text(),'the box explains what ticking it means')
    page.locator('#ruleMoveUnread').uncheck();page.wait_for_timeout(100)
    page.click('#addCondition');check(page.locator('.condition-row').count()==2,'add condition')
    page.locator('.remove-condition').first.click();check(page.locator('.condition-row').count()==1,'remove condition')
    page.click('#newRule');page.fill('#ruleName','<img src=x onerror=alert(1)>')
    page.select_option('#source','demo-in');page.select_option('#target','demo-fin')
    page.locator('.condition-row input').fill('invoices.example')
    page.click('#save');page.wait_for_function("document.querySelectorAll('.rule-row').length===4")
    check(page.locator('.rule-open strong').last.inner_text().startswith('<img'),'rule name rendered as literal text')
    check(page.locator('#ruleList img').count()==0,'no HTML injection from rule name')
    page.click('#up');page.wait_for_function("document.querySelectorAll('.rule-open strong')[2].textContent.startsWith('<img')")
    check(True,'priority order can be changed')
    page.click('#addBranch');check(page.locator('.branch-row').count()==1,'branch row can be added')
    page.locator('.branch-row').last.locator('input').fill('Order')
    page.locator('.branch-row').last.locator('select').last.select_option('demo-buy')
    page.click('#save');page.wait_for_function("document.querySelectorAll('.rule-open strong')[0].textContent==='Fortnox fakturor'")
    check(True,'rule with branches saved')
    page.click('#runAllRulesBtn')
    page.wait_for_function("document.getElementById('toast').textContent.includes('Granskade')")
    check('matchade och köades' in page.locator('#toast').inner_text(),'run-all button reports what happened')
    check('inkommande mejl bevakas' in page.locator('#autoRunInfo').inner_text().lower(),'status says incoming mail stays monitored')
    page.locator('.rule-open:has-text("Arkivera äldre mejl")').click()
    date_op=page.locator('.condition-row').first.locator('select').nth(1)
    check(date_op.input_value()=='older','archive rule uses an age condition that rolls forward')
    page.click('#addCondition')
    row=page.locator('.condition-row').last
    row.locator('select').first.select_option('date');page.wait_for_timeout(50)
    row.locator('select').nth(1).select_option('beforeThisYear');page.wait_for_timeout(50)
    check(row.locator('select').nth(1).input_value()=='beforeThisYear','rolling year condition is still available')
    check(row.locator('input').is_disabled(),'rolling year condition needs no value')
    row.locator('.remove-condition').click()
    check(page.locator('.condition-row').count()==1,'test condition removed')
    page.click('#diagnoseBtn')
    page.wait_for_function("document.getElementById('diagnosePanel').hidden===false&&/matchade regeln/.test(document.getElementById('diagnosePanel').textContent)")
    panel=page.locator('#diagnosePanel').inner_text()
    check('olästa och väntar' in panel,'diagnosis explains unread mail waiting')
    check(page.locator('#diagnosePanel .diagnose-row').count()==3,'diagnosis lists matching examples')
    check('Testläge' in panel,'diagnosis reminds about test mode')
    fix=page.locator('#diagnosePanel button:has-text("Tillåt olästa")')
    check(fix.count()==1,'diagnosis offers to allow unread mail')
    fix.click()
    page.wait_for_function("document.getElementById('ruleReadFilter').value==='both'")
    check('olästa & lästa direkt' in page.locator('.rule-row:has-text("Arkiv – äldre än 90 dagar") .rule-tag').inner_text(),'unread mail is allowed and saved for that rule')
    check(page.locator('.rule-row:has-text("Arkiv – äldre än 90 dagar") .rule-inline-opts input').first.is_checked(),'the rule list checkbox now says unread mail moves')
    page.click('#catchUp')
    page.wait_for_function("document.getElementById('toast').textContent.includes('Skannade 5')")
    check('köade 2' in page.locator('#toast').inner_text(),'catch-up in preview reports scanned and queued counts')
    with page.expect_download() as info:page.click('#export')
    with tempfile.TemporaryDirectory() as temp:
        file=Path(temp)/'rules.json';info.value.save_as(file)
        data=json.loads(file.read_text());check(data['format']=='lasfilter-rules' and len(data['rules'])==4 and any(len(r.get('branches',[]))==1 for r in data['rules']) and any(len(r.get('branches',[]))==2 for r in data['rules']),'exported JSON keeps branch rows')
        page.set_input_files('#import',file)
        page.wait_for_function("document.getElementById('statusPill').textContent.includes('pausad')")
        check('pausad' in page.locator('#statusPill').inner_text(),'import pauses preview automation')
    page.click('[data-view=settings]');page.select_option('#theme','dark')
    page.wait_for_function("document.documentElement.dataset.theme==='dark'")
    check(True,'dark theme')
    page.select_option('#fontSize','18');page.wait_for_function("getComputedStyle(document.documentElement).fontSize==='18px'")
    check(True,'font size actually affects root text size')
    check(page.locator('#moveMode').count()==1 and page.locator('#openWindow').count()==1 and page.locator('#hourly').count()==1,'direct-mode and sweep settings exist')
    page.select_option('#moveMode','direct')
    page.wait_for_function("document.getElementById('moveMode').value==='direct'")
    check(True,'direct move mode can be selected')
    page.uncheck('#openWindow');page.wait_for_timeout(150)
    check(not page.is_checked('#openWindow'),'window indicator toggle persists')
    page.select_option('#moveMode','read');page.wait_for_function("document.getElementById('moveMode').value==='read'")
    check(True,'move mode can be switched back')
    page.check('#verbose');page.wait_for_timeout(150)
    check(page.is_checked('#verbose'),'verbose debug log toggle persists')
    page.set_viewport_size({'width':720,'height':900})
    check(page.evaluate('document.documentElement.scrollWidth<=innerWidth'),'settings fit narrow viewport at 18 px')
    page.click('[data-view=rules]')
    check(page.evaluate('document.documentElement.scrollWidth<=innerWidth'),'editor fits narrow viewport at 18 px')
    page.click('[data-view=activity]');check(page.locator('#logRows tr').count()>0,'activity view renders')
    page.click('[data-view=help]');check(page.locator('#view-help').is_visible(),'help view renders')
    check(not external,'UI makes no external network requests')
    check(not errors,'no uncaught UI exceptions')
    plain=b.new_page();plain.goto((ROOT/'addon'/'ui.html').as_uri());plain.wait_for_selector('#notice:not([hidden])')
    check('installerat Thunderbird' in plain.locator('#notice').inner_text(),'standalone source does not pretend to be connected')
    b.close()
print('UI CHECKS OK',len(checks))
